#!/usr/bin/env python3
"""Emit the split upper K tiling shards ArealUK/ChunkNNNN.lean (two leaves each; chord leaves checked through four
kernel-checked segments of the node pass, see ArealUK/Seg.lean) from ArealUK/chunks.json (written by tools/genK_U5b.sh)
and the native helper's accumulator lines (`arlseg S LO HI`, concatenated). The shard statements are those of
tools/genK_U5b.sh, so Areal/UCert/LeavesKG/* and LeavesK.lean are unchanged.
usage: python3 -I tools/genKsplit_U5b.py S SEGS.txt"""
import json, os, sys
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = int(sys.argv[1])
segs = {}
for line in open(sys.argv[2]):
    f = line.rstrip('\n').split('\t')
    segs[int(f[0])] = f
rows = json.load(open(f'{H}/ArealUK/chunks.json'))
lv = json.load(open(f'{H}/data/leaves_U5b.json'))
assert len(segs) == sum(r[2] for r in rows), (len(segs), sum(r[2] for r in rows))
def leaf_lit(f):
    return f'⟨{f[1]}, {f[2]}, {f[3]}, {f[4]}, {f[5]}, {f[6]}⟩'
for name, a, n, X1, k1, X2, k2 in rows:
    ci = int(name[5:])
    sl = [segs[a + j] for j in range(n)]
    assert sl[0][2] == str(X1) and sl[0][4] == str(k1), (name, sl[0][:5], X1, k1)
    o = ['import ArealUCore.Lits', 'import ArealUCore.Leaves', 'import ArealUK.Seg', '',
         f'/-! Shard {ci} of the areal U5b tiling (K, node pass in four kernel-checked segments): leaves {a} .. {a + n - 1}.',
         'Generated by tools/genKsplit_U5b.py. -/', '', 'set_option maxRecDepth 200000', 'set_option maxHeartbeats 0', '',
         'namespace ArealUCore.ArealUK', '', 'open ArealUCore', '']
    facts = []
    for j, f in enumerate(sl):
        kind, Xp, Xq, k, x0q, mask = f[1], f[2], f[3], f[4], f[5], f[6]
        if kind == '0':
            A = f[7:11]
            fn = f'(leafStep ctxLitU.tab ctxLitU.l2 {k} {Xp} {Xq} (logT ctxLitU.tab ctxLitU.l2 (DEC * 2 ^ {k}) 1))'
            lists = [f'(ctxLitU.rs.take {S})', f'((ctxLitU.rs.drop {S}).take {S})', f'(((ctxLitU.rs.drop {S}).drop {S}).take {S})',
                     f'(((ctxLitU.rs.drop {S}).drop {S}).drop {S})']
            inits = ['⟨0, 0, 0, 0, 0, false⟩'] + A[:3]
            for q in range(4):
                o.append(f'theorem s{ci}_{j}_{q} : {lists[q]}.foldl {fn} {inits[q]} = {A[q]} := by decide +kernel')
            o.append(f'theorem f{ci}_{j} : chordFinOK ctxLitU {Xp} {Xq} {k} {x0q} {mask} {A[3]} = true := by decide +kernel')
            o.append('')
            facts.append(f'(leafOK_chord _ _ _ _ _ _ (chordOK_of_segs _ _ _ _ _ _ {S} _ _ _ _ s{ci}_{j}_0 s{ci}_{j}_1 s{ci}_{j}_2 s{ci}_{j}_3 f{ci}_{j}))')
        else:
            o.append(f'theorem w{ci}_{j} : windowOK ctxLitU {Xp} {Xq} {k} = true := by decide +kernel')
            o.append('')
            facts.append(f'(leafOK_window _ _ _ _ _ _ w{ci}_{j})')
    assert n == 2, name
    o.append(f'theorem chunk_{ci:04d} :')
    o.append(f'    leavesOK ctxLitU {X1} {k1} ((leaves.drop {a}).take {n}) {X2} {k2} = true := by')
    o.append(f'  have hl : (leaves.drop {a}).take {n} = [{", ".join(leaf_lit(f) for f in sl)}] := by decide +kernel')
    o.append('  rw [hl]')
    o.append(f'  exact leavesOK_two _ _ _ _ _ _ _ (by decide +kernel) {facts[0]} (by decide +kernel) {facts[1]} (by decide +kernel)')
    o.append('')
    o.append('end ArealUCore.ArealUK')
    open(f'{H}/ArealUK/{name}.lean', 'w').write('\n'.join(o) + '\n')
print('split shards', len(rows), 'S', S)
